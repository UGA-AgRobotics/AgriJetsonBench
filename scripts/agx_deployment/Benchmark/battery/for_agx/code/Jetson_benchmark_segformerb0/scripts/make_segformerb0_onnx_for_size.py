#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, List


def _prefer_active_env_site_packages() -> None:
    prefix = os.environ.get("CONDA_PREFIX") or os.environ.get("VIRTUAL_ENV") or sys.prefix
    major = sys.version_info.major
    minor = sys.version_info.minor
    site_path = Path(prefix) / "lib" / f"python{major}.{minor}" / "site-packages"
    if site_path.exists():
        site_str = str(site_path.resolve())
        try:
            sys.path.remove(site_str)
        except ValueError:
            pass
        sys.path.insert(0, site_str)

    # Avoid protobuf namespace pollution from user-site packages on Jetson.
    for name in list(sys.modules):
        if name == "google" or name.startswith("google."):
            sys.modules.pop(name, None)


_prefer_active_env_site_packages()

import onnx


def _dim_to_python(dim: onnx.TensorShapeProto.Dimension) -> int | str | None:
    if dim.HasField("dim_value"):
        return int(dim.dim_value)
    if dim.HasField("dim_param"):
        return str(dim.dim_param)
    return None


def _shape(value_info: Any) -> list[int | str | None]:
    return [_dim_to_python(d) for d in value_info.type.tensor_type.shape.dim]


def _is_dynamic_dim(value: int | str | None) -> bool:
    return value is None or isinstance(value, str) or int(value) <= 0


def _set_dim(dim: onnx.TensorShapeProto.Dimension, value: int | str) -> None:
    dim.Clear()
    if isinstance(value, str):
        dim.dim_param = value
    else:
        dim.dim_value = int(value)


def _patch_4d_shape(value_info: Any, size: int, batch: int = 1, channels: int | None = None) -> None:
    dims = value_info.type.tensor_type.shape.dim
    if len(dims) != 4:
        return
    _set_dim(dims[0], batch)
    if channels is not None:
        _set_dim(dims[1], int(channels))
    _set_dim(dims[2], int(size))
    _set_dim(dims[3], int(size))


def _run_export_template(template: str, size: int, output: Path, source_onnx: Path) -> None:
    # Optional hook for users whose static ONNX cannot be patched and must be re-exported from PyTorch.
    # Supported placeholders: {size}, {output}, {onnx}
    cmd_text = template.format(size=size, output=str(output), onnx=str(source_onnx))
    subprocess.run(cmd_text, shell=True, check=True)


def make_onnx_for_size(
    *,
    source_onnx: Path,
    output_onnx: Path,
    size: int,
    patch_static: bool,
    export_command_template: str | None,
) -> dict[str, Any]:
    source_onnx = source_onnx.expanduser().resolve()
    output_onnx = output_onnx.expanduser().resolve()
    output_onnx.parent.mkdir(parents=True, exist_ok=True)

    if export_command_template:
        _run_export_template(export_command_template, size, output_onnx, source_onnx)
        model = onnx.load(str(output_onnx))
        onnx.checker.check_model(model)
        in_shape = _shape(model.graph.input[0])
        out_shape = _shape(model.graph.output[0]) if model.graph.output else []
        return {
            "method": "export_command_template",
            "source_onnx": str(source_onnx),
            "output_onnx": str(output_onnx),
            "requested_size": int(size),
            "input_shape": in_shape,
            "output_shape": out_shape,
            "note": "ONNX was generated by SEGFORMERB0_EXPORT_COMMAND_TEMPLATE.",
        }

    model = onnx.load(str(source_onnx))
    if not model.graph.input:
        raise RuntimeError(f"ONNX model has no graph inputs: {source_onnx}")
    input_shape = _shape(model.graph.input[0])
    output_shape = _shape(model.graph.output[0]) if model.graph.output else []
    if len(input_shape) != 4:
        raise RuntimeError(f"Expected 4D SegFormer-B0 input tensor, got {input_shape}")

    h = input_shape[2]
    w = input_shape[3]
    input_is_dynamic = _is_dynamic_dim(h) or _is_dynamic_dim(w)
    input_matches_size = (not _is_dynamic_dim(h)) and (not _is_dynamic_dim(w)) and int(h) == int(size) and int(w) == int(size)

    if input_is_dynamic or input_matches_size:
        shutil.copy2(source_onnx, output_onnx)
        method = "copy_dynamic_onnx" if input_is_dynamic else "copy_static_matching_size"
    else:
        if not patch_static:
            raise RuntimeError(
                "The ONNX input is static and does not match the requested size. "
                f"source_shape={input_shape}, requested={size}. "
                "Either set --patch-static-shape or provide SEGFORMERB0_EXPORT_COMMAND_TEMPLATE."
            )
        # SegFormer-B0 is fully convolutional in the typical export. For resolution discovery we patch
        # the declared input/output H/W. TensorRT will still reject the model if the graph has hidden
        # fixed-size ops, which is exactly what we want the discovery script to record as build failure.
        channels = int(input_shape[1]) if not _is_dynamic_dim(input_shape[1]) else 3
        _patch_4d_shape(model.graph.input[0], size=size, batch=1, channels=channels)
        for out in model.graph.output:
            if len(out.type.tensor_type.shape.dim) == 4:
                # Keep output channel/class dimension as declared, change spatial H/W to requested size.
                out_channels = _dim_to_python(out.type.tensor_type.shape.dim[1])
                ch_int = int(out_channels) if isinstance(out_channels, int) and out_channels > 0 else None
                _patch_4d_shape(out, size=size, batch=1, channels=ch_int)
        # Drop stale intermediate shape annotations; they are not required by TensorRT and often contain
        # the original fixed 640x640 dimensions.
        del model.graph.value_info[:]
        onnx.checker.check_model(model)
        onnx.save(model, str(output_onnx))
        method = "patched_static_shape"

    patched = onnx.load(str(output_onnx))
    onnx.checker.check_model(patched)
    final_input_shape = _shape(patched.graph.input[0])
    final_output_shape = _shape(patched.graph.output[0]) if patched.graph.output else []
    return {
        "method": method,
        "source_onnx": str(source_onnx),
        "output_onnx": str(output_onnx),
        "requested_size": int(size),
        "source_input_shape": input_shape,
        "source_output_shape": output_shape,
        "final_input_shape": final_input_shape,
        "final_output_shape": final_output_shape,
        "patch_static_shape_enabled": bool(patch_static),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description="Create a SegFormer-B0 ONNX copy for an exact input size used by resolution ablation.")
    ap.add_argument("--source-onnx", required=True)
    ap.add_argument("--output-onnx", required=True)
    ap.add_argument("--imgsz", type=int, required=True)
    ap.add_argument("--patch-static-shape", action="store_true", help="Patch declared static ONNX H/W if source ONNX is fixed at another size.")
    ap.add_argument("--export-command-template", default=os.environ.get("SEGFORMERB0_EXPORT_COMMAND_TEMPLATE"), help="Optional shell command used to re-export ONNX. Placeholders: {size}, {output}, {onnx}.")
    ap.add_argument("--out-json", default=None)
    args = ap.parse_args()

    meta = make_onnx_for_size(
        source_onnx=Path(args.source_onnx),
        output_onnx=Path(args.output_onnx),
        size=int(args.imgsz),
        patch_static=bool(args.patch_static_shape),
        export_command_template=args.export_command_template,
    )
    if args.out_json:
        out_json = Path(args.out_json).expanduser().resolve()
        out_json.parent.mkdir(parents=True, exist_ok=True)
        out_json.write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
